// Command gen writes the generated mode registry,
// internal/modes/all/registry_gen.go, from the directory listing of
// internal/modes: every sibling directory holding a preamble.md is a mode
// package (STYLE.md §1, §10). It runs from internal/modes via the
// //go:generate directive in generate.go; the output is deterministic and
// gofmt-formatted, so two branches adding two modes never conflict on a
// hand-edited line.
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"forge/internal/core/model"
)

func main() {
	dir, err := os.Getwd()
	if err != nil {
		fatal(err)
	}
	out, err := generate(dir)
	if err != nil {
		fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(dir, "all"), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "all", "registry_gen.go"), out, 0o644); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "modes/gen:", err)
	os.Exit(1)
}

// generate renders the registry source from the mode directories under
// modesDir. A directory is a mode package iff it contains a preamble.md, so
// gen, all, and schema are never listed; names are validated because they
// become import paths and registry keys.
func generate(modesDir string) ([]byte, error) {
	entries, err := os.ReadDir(modesDir)
	if err != nil {
		return nil, fmt.Errorf("list %s: %w", modesDir, err)
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		if _, err := os.Stat(filepath.Join(modesDir, e.Name(), "preamble.md")); err != nil {
			if os.IsNotExist(err) {
				continue
			}
			return nil, fmt.Errorf("stat %s/preamble.md: %w", e.Name(), err)
		}
		if err := model.ValidateName(e.Name()); err != nil {
			return nil, fmt.Errorf("mode directory: %w", err)
		}
		names = append(names, e.Name())
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("no mode packages under %s", modesDir)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("// Code generated by modes/gen. DO NOT EDIT.\n\n")
	b.WriteString("// Package all holds the generated mode registry list: one import and one\n")
	b.WriteString("// New() call per mode package under internal/modes (STYLE.md §1, §10). It is\n")
	b.WriteString("// a child of modes rather than modes itself because every mode package\n")
	b.WriteString("// imports modes for the Mode interface, and a package cannot import its own\n")
	b.WriteString("// importers.\n")
	b.WriteString("package all\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"forge/internal/modes\"\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q\n", "forge/internal/modes/"+n)
	}
	b.WriteString(")\n\n")
	b.WriteString("// All returns one value of every mode, sorted by name; cmd/forge feeds it\n")
	b.WriteString("// to modes.NewRegistry and modes.Seeds.\n")
	b.WriteString("func All() []modes.Mode {\n\treturn []modes.Mode{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t\t%s.New(),\n", n)
	}
	b.WriteString("\t}\n}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format registry: %w", err)
	}
	return src, nil
}
