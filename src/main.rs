#[cfg(test)]
mod readme_layout {
    use std::fs;
    use std::path::Path;

    // README.md's "Layout" section is generated by hand, not by the
    // compiler, so nothing stops it drifting from the tree the way rustc
    // stops a stale `mod` list. This test is that stop: every source file
    // and workspace crate has to be named there, or it fails.
    #[test]
    fn every_module_and_crate_is_named_in_the_readme() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"));
        let readme = fs::read_to_string(root.join("README.md")).expect("read README.md");

        let mut missing = Vec::new();

        for dir in ["src", "src/store"] {
            for entry in fs::read_dir(root.join(dir)).expect("read_dir") {
                let path = entry.expect("dir entry").path();
                if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                    continue;
                }
                let name = path.file_name().unwrap().to_str().unwrap().to_string();
                if !readme.contains(&name) {
                    missing.push(format!("{dir}/{name}"));
                }
            }
        }

        let cargo_toml = fs::read_to_string(root.join("Cargo.toml")).expect("read Cargo.toml");
        let members_line = cargo_toml
            .lines()
            .find(|l| l.trim_start().starts_with("members"))
            .expect("workspace members line in Cargo.toml");
        for member in members_line
            .split(['[', ']', '"', ',', '='])
            .map(|s| s.trim())
            .filter(|s| !s.is_empty() && *s != "members")
        {
            if !readme.contains(&format!("{member}/")) {
                missing.push(format!("workspace member {member}"));
            }
        }

        assert!(
            missing.is_empty(),
            "README.md's Layout section doesn't name: {missing:?}"
        );
    }
}

#[cfg(test)]
mod docs_readme_index {
    use std::fs;
    use std::path::Path;

    // docs/README.md is the hand-written index of everything under docs/.
    // This is the stop that keeps it from going stale: every docs/*.md file
    // has to be named there, and every *.md name it mentions has to exist.
    #[test]
    fn every_doc_is_indexed_and_the_index_names_only_real_files() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"));
        let docs = root.join("docs");
        let index = fs::read_to_string(docs.join("README.md")).expect("read docs/README.md");

        let mut missing = Vec::new();
        for entry in fs::read_dir(&docs).expect("read_dir docs") {
            let path = entry.expect("dir entry").path();
            if path.extension().and_then(|e| e.to_str()) != Some("md") {
                continue;
            }
            let name = path.file_name().unwrap().to_str().unwrap().to_string();
            if name == "README.md" {
                continue;
            }
            if !index.contains(&name) {
                missing.push(name);
            }
        }
        assert!(
            missing.is_empty(),
            "docs/README.md doesn't index: {missing:?}"
        );

        let mut dangling = Vec::new();
        for word in index.split(|c: char| c.is_whitespace() || "[]()`,*:/".contains(c)) {
            let Some(stem) = word.strip_suffix(".md") else {
                continue;
            };
            let name = format!("{stem}.md");
            if !docs.join(&name).is_file() {
                dangling.push(name);
            }
        }
        assert!(
            dangling.is_empty(),
            "docs/README.md names files that don't exist: {dangling:?}"
        );
    }
}
